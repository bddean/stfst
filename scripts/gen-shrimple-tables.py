#!/usr/bin/env python3
"""Turn Shrimple's three tables into xfst defines.

The tables are imported data with an upstream owner (`Shrimple-WSI-English.py`,
forked from @Jalexu's), so they are transcribed rather than authored, the same
standing as `typey-type-full.json`. The *grammar* over them is hand-written in
`dictionaries/shrimple.xfst`; only this data is generated.

Two things this has to get right. Plover writes a chord fragment in Plover order
(`*A`), and the tape wants steno order (`A*`), so every key is sorted by the
system's `order`. And a vowel entry straddles the star position (`AO` before it,
`EU` after), so each vowel is emitted as its two halves with the value on the
first, which is what lets the star sit between them and belong to whichever
table claims it.

Usage: scripts/gen-shrimple-tables.py > dictionaries/shrimple-tables.xfst
"""
import importlib.util
import os
import sys

ORDER = "#@^+STKPWHRAO*EUfrpblgtsdz"
# Plover writes the right bank in upper case; the tape gives it lower case, so a
# key is one symbol and no hyphen is needed.
RIGHT = {"F": "f", "R": "r", "P": "p", "B": "b", "L": "l",
         "G": "g", "T": "t", "S": "s", "D": "d", "Z": "z"}


def load(path):
    spec = importlib.util.spec_from_file_location("shrimple", path)
    module = importlib.util.module_from_spec(spec)
    # It prints on import, which would land in the generated file.
    out, sys.stdout = sys.stdout, sys.stderr
    try:
        spec.loader.exec_module(module)
    finally:
        sys.stdout = out
    return module


def tape(fragment, right_bank):
    """A Plover chord fragment as tape symbols in steno order."""
    out = []
    for c in fragment:
        if c == "-":
            continue          # Plover's hyphen is notation, not a key
        symbol = RIGHT[c] if right_bank else c
        if symbol not in ORDER:
            raise SystemExit(f"{fragment!r}: {c!r} is not a key")
        out.append(symbol)
    return "".join(sorted(out, key=ORDER.index))


def literal(text):
    """An xfst literal: `{...}` with every non-alphanumeric escaped."""
    if text == "":
        return "0"
    body = "".join(("%" + c if not c.isalnum() else c) for c in text)
    return "{" + body + "}"


def pair(keys, value):
    upper = literal(keys) if keys else "0"
    return f"[ {upper} .x. {literal(value)} ]"


def emit(name, rows, doc):
    print(f"! {doc}")
    if not rows:
        print(f"define {name} [ 0 .x. 0 ] ;\n")
        return
    print(f"define {name} [ {rows[0]}")
    for row in rows[1:]:
        print(f"  | {row}")
    print("] ;\n")


def main(path):
    shrimple = load(path)
    print("! Generated by scripts/gen-shrimple-tables.py. Edit that, not this.")
    print(f"! Tables from {os.path.basename(path)}.\n")

    # Starters and enders are plain chord-to-text, split by whether the entry
    # claims the asterisk.
    for table, name, right, doc in (
        (shrimple.starter_letter, "Starter", False, "left bank to text"),
        (shrimple.ender_letter, "Ender", True, "right bank to text"),
    ):
        plain, starred = [], []
        for keys, value in table.items():
            # The empty key is the grammar's business: a syllable need not have
            # a starter or an ender, and a table that accepts the empty string
            # makes `Table+` accept it too, any number of times.
            if keys == "":
                continue
            # `^` is not text. It marks the word as attached, which is a record
            # flag, so the grammar handles it.
            if keys == "^":
                continue
            star = keys.startswith("*")
            body = tape(keys.lstrip("*"), right)
            (starred if star else plain).append(pair(body, value))
        emit(name, plain, f"{doc}, no asterisk")
        emit(name + "Star", starred, f"{doc}, claims the asterisk")

    # A vowel straddles the star, so it is two halves with the value on the AO
    # side. `Vowel` is what the tape reads before the star; `VowelEU` after.
    plain, starred = [], []
    for keys, value in shrimple.vowels.items():
        if keys in ("", "-"):
            continue
        star = keys.startswith("*")
        body = tape(keys.lstrip("*"), False)
        ao = "".join(c for c in body if c in "AO")
        eu = "".join(c for c in body if c in "EU")
        row = f"[ {pair(ao, value)} SLOT {pair(eu, '')} ]"
        (starred if star else plain).append(row)
    emit("VowelBody", [r.replace(" SLOT ", " ") for r in plain],
         "vowel halves with nothing between them")
    emit("VowelStarBody", [r.replace(" SLOT ", " [ \"*\" .x. 0 ] ") for r in starred],
         "vowel halves with the asterisk between them, claimed by the vowel")
    emit("VowelSplitBody", [r.replace(" SLOT ", " [ \"*\" .x. 0 ] ") for r in plain],
         "vowel halves with the asterisk between them, claimed by someone else")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1
         else os.path.expanduser("~/.config/plover/Shrimple-WSI-English.py"))

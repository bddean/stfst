#!/usr/bin/env python3
"""Golden cases for the phrasing prototype, with `phrasing.py` as the oracle.

The prototype's domain is small enough to cover exhaustively: 128 left-key sets
times four modality corners times negation times tense times the two contraction
modes is 4,096 strokes, every one of them checked against the Python. So there is
no sampling and no judgement about which cases matter.

A stroke with no subject is a modifier, not a clause (§4.1), and the Python
raises for it. Those cases stay in the file with no expectation, which asserts the
stronger thing: this dictionary has no entry for them.

Usage: scripts/gen-golden-phrasing.py > tests/golden/phrasing.tsv
"""
import contextlib
import importlib.util
import io
import itertools
import os
import subprocess
import sys

LEFT = "STKPWHR"
STFST = os.path.join(os.path.dirname(__file__), "..", "target", "release", "stfst")
SYSTEM = os.path.join(os.path.dirname(__file__), "..", "systems",
                      "stenotype-extended.toml")


def load(path):
    spec = importlib.util.spec_from_file_location("phrasing", path)
    module = importlib.util.module_from_spec(spec)
    with contextlib.redirect_stdout(io.StringIO()):
        spec.loader.exec_module(module)
    return module


def tapes_for(outlines):
    """Every outline as a key tape, via the compiler's own parser."""
    joined = "\n".join(outlines) + "\n"
    out = subprocess.run(
        [STFST, "tape", "--system", SYSTEM], input=joined,
        capture_output=True, text=True, check=True).stdout
    table = {}
    for line in out.splitlines():
        fields = line.split("\t")
        if len(fields) >= 2 and fields[1] != "!":
            table[fields[0]] = fields[1]
    return table


def stroke(full, left, ao, star, past):
    """A Plover stroke assembled from its fields.

    Notation is positional: the hyphen appears only when nothing in the middle
    already separates the banks.
    """
    out = ("^" if full else "") + "+" + left + ao + ("*" if star else "")
    if past:
        out += ("-" if not (ao or star) else "") + "D"
    return out


def main(path):
    ph = load(path)
    strokes = []
    for n in range(len(LEFT) + 1):
        for combo in itertools.combinations(LEFT, n):
            for ao in ("", "A", "O", "AO"):
                for star in (False, True):
                    for past in (False, True):
                        for full in (False, True):
                            strokes.append(
                                stroke(full, "".join(combo), ao, star, past))

    tapes = tapes_for(strokes)
    lines = [
        "! The phrasing prototype, every stroke in its domain: %d of them."
        % len(strokes),
        "! Expectations come from phrasing.py, so this file is an oracle and not a",
        "! snapshot of our output. A line with no expectation asserts there is no",
        "! entry, which is what a chord with no subject must have.",
        "! Generated by scripts/gen-golden-phrasing.py; edit that, not this.",
    ]
    seen = set()
    for s in strokes:
        tape = tapes.get(s)
        if tape is None or tape in seen:
            continue
        seen.add(tape)
        try:
            answer = ph.lookup((s,))
        except (KeyError, IndexError):
            answer = None
        lines.append(tape if answer is None else tape + "\t" + answer)
    print("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1
         else os.path.expanduser("~/.config/plover/phrasing.py"))

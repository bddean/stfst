#!/usr/bin/env python3
"""Golden cases for emily-symbols, taken from emily-symbols.py's own table.

Reading the table rather than our output is the point: the file is then an
oracle, and a transcription error in the xfst shows up as a failure.
"""
import importlib.util
import os
import pathlib
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "plover-plugin"))
from plover_stfst.record import Record

SRC = pathlib.Path.home() / '.config/plover/emily-symbols.py'
OUT = pathlib.Path(__file__).resolve().parent.parent / 'tests/golden/emily-symbols.tsv'

spec = importlib.util.spec_from_file_location('em', SRC)
em = importlib.util.module_from_spec(spec)
spec.loader.exec_module(em)

def record(translation):
    return str(Record.from_translation(translation))


lines = [
    "! emily-symbols. Glyph cells come from emily-symbols.py's own table, so this",
    '! file is an oracle and not a snapshot of our output.',
    '! Generated by scripts/gen-golden-emily.py; edit that, not this.',
]
variant_keys = ['', 'A', 'O', 'AO']
for pattern, value in em.symbols.items():
    for v in range(4):
        want = value[v] if isinstance(value, list) else value
        lines.append(f'#{pattern}{variant_keys[v]}U\t{record(want)}')

lines += [
    '! modifiers, which are rules rather than table data',
    '#HRUr\t![ATTACH_L]',
    '#HRUb\t![ATTACH_R]',
    '#HRUrb\t![ATTACH_L][ATTACH_R]',
    '#HRUg\t![CAP_NEXT]',
    '#HRUs\t![REP2]',
    '#HRUt\t![REP3]',
    '#HRUts\t![REP4]',
    '#HRUrbg\t![ATTACH_L][ATTACH_R][CAP_NEXT]',
    '#HRUrbgts\t![ATTACH_L][ATTACH_R][CAP_NEXT][REP4]',
    '! both halves of the identifier are required, so these have no entry',
    '#HR',
    'HRU',
]
OUT.write_text('\n'.join(lines) + '\n')
print(f'{sum(1 for l in lines if not l.startswith("!"))} cases -> {OUT}')

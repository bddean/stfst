#!/usr/bin/env python3
"""Golden cases for emily-symbols, taken from emily-symbols.py's own answers.

Calling `lookup` rather than reading the table is the point: the table is only
the glyphs, and the attachment, capitalisation and repetition keys are rules on
top of it. A generator that read the table alone was an oracle for a third of the
dictionary, and the `-R`/`-B` polarity was inverted here for as long as it ran.

So every stroke the Python accepts is asked, which is every combination of the
seven fields.
"""
import importlib.util
import itertools
import os
import pathlib
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "plover-plugin"))
from plover_stfst.record import Record

SRC = pathlib.Path.home() / '.config/plover/emily-symbols.py'
OUT = pathlib.Path(__file__).resolve().parent.parent / 'tests/golden/emily-symbols.tsv'

spec = importlib.util.spec_from_file_location('em', SRC)
em = importlib.util.module_from_spec(spec)
spec.loader.exec_module(em)

lines = [
    "! emily-symbols. Every expectation is emily-symbols.py's own answer, so this",
    '! file is an oracle and not a snapshot of our output.',
    '! Generated by scripts/gen-golden-emily.py; edit that, not this.',
]
# The seven fields in steno order, right bank lowercase because that is the tape.
FIELDS = [['', 'A', 'O', 'AO'], ['', 'r', 'b', 'rb'], ['', 'g'],
          ['', 's', 't', 'ts']]
REPEATS = {'': 1, 's': 2, 't': 3, 'ts': 4}


def expect(base, answer, count):
    """The oracle's record, with a repeated body named rather than written out.

    The one field where the two languages say the same thing differently: the
    Python writes the glyph `count` times and the record language counts it. The
    fold is proved per stroke by spelling it back, so a Python that repeated
    something else fails here instead of passing quietly.
    """
    want = Record.from_translation(answer)
    if count < 2:
        return want
    folded = Record.from_translation(base)
    folded.repeat = count
    if folded.translation() != want.translation():
        raise AssertionError('%r is not %d of %r' % (answer, count, base))
    return folded


for pattern in em.symbols:
    for variant, attach, cap, repeat in itertools.product(*FIELDS):
        tape = '#%s%sU%s%s%s' % (pattern, variant, attach, cap, repeat)

        def ask(rep):
            stroke = '#%s%sU%s%s%s' % (pattern, variant, attach.upper(),
                                       cap.upper(), rep.upper())
            try:
                return em.lookup((stroke,))
            except KeyError:
                return None

        answer = ask(repeat)
        if answer is None:
            lines.append(tape)          # no tab: no entry
            continue
        lines.append('%s\t%s' % (tape, expect(ask(''), answer, REPEATS[repeat])))

lines += [
    '! both halves of the identifier are required, so these have no entry',
    '#HR',
    'HRU',
]
OUT.write_text('\n'.join(lines) + '\n')
print(f'{sum(1 for l in lines if not l.startswith("!"))} cases -> {OUT}')

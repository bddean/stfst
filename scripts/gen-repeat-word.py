#!/usr/bin/env python3
"""Transcribe repeat-word.py's stems into a flat dictionary.

The Python is a *meta* plugin: `^SKP` looks up `{:repeat_word:and}`, and the meta
reads Plover's output history to find the last word, because a plain lookup
cannot. The record language can say it directly:

    ^SKP    and [COPY1]

`[COPY1]` is the host's first bound word, spliced without the transducer reading
it, so the whole plugin becomes one entry per stem and the meta disappears. That
is host contract item 5's register half, and it is the smallest thing that shows
why the half exists.

Nothing here is a rule, so this is a flat source rather than a grammar. It is
generated only so that the stem list cannot drift from the Python's.

Usage: scripts/gen-repeat-word.py > dictionaries/repeat-word.dict
"""
import contextlib
import importlib.util
import io
import os
import sys


def load(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    with contextlib.redirect_stdout(io.StringIO()):
        spec.loader.exec_module(module)
    return module


def main(path):
    rw = load(path, "repeat_word")
    print("\n".join([
        "! repeat-word: a connective, then the previous word again.",
        "!",
        "! The X-conn-X reduplication steno otherwise has to spell twice: back and",
        "! back, side by side, more and more. `^` folded onto a connective's own",
        "! brief means \"write this connective, then echo the last word\".",
        "!",
        "! `[COPY1]` is the word the host has bound to its first register. The",
        "! dictionary never sees it, which is what keeps the automaton finite: a",
        "! transducer that had to know the word would need a path per word.",
        "!",
        "! Generated by scripts/gen-repeat-word.py from repeat-word.py.",
        "",
    ]))
    for conn, stems in rw.STEMS.items():
        for stem in stems:
            # The space is the word boundary inside one record, so the host puts
            # no space of its own between the two halves.
            print("%s\t%s [COPY1]" % (stem, conn))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1
         else os.path.join(os.path.dirname(__file__), "..", "dictionaries", "repeat-word.py"))

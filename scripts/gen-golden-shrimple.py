#!/usr/bin/env python3
"""Golden cases for Shrimple, with `Shrimple-WSI-English.py` as the oracle.

The Python is the specification, so its answers are the expectations and this
file is an oracle rather than a snapshot of our output. It covers each table
separately, which is where a transcription error would be, and then whole
syllables and multi-stroke words, which is where the segmentation and the
asterisk cascade would be.

Skipped: any case whose Python answer holds a `{}` directive. A directive in the
middle of a translation is Plover's in-band syntax and a record has nowhere to
put it, so those cases are a question about the port and not about this table.

Usage: scripts/gen-golden-shrimple.py > tests/golden/shrimple.tsv
"""
import contextlib
import importlib.util
import io
import itertools
import os
import subprocess
import sys

# Plover notation needs position to be read (`T` is left bank, `-T` is right),
# so the tape comes from `stfst tape`, which is the parser the compiler uses and
# which agrees with Plover on all 145,345 typey-type outlines. Doing it here with
# a letter table looked fine and put every left-bank key on the right bank.
STFST = os.path.join(os.path.dirname(__file__), "..", "target", "release", "stfst")
SYSTEM = os.path.join(os.path.dirname(__file__), "..", "systems",
                      "stenotype-extended.toml")


def load(path):
    spec = importlib.util.spec_from_file_location("shrimple", path)
    module = importlib.util.module_from_spec(spec)
    with contextlib.redirect_stdout(io.StringIO()):
        spec.loader.exec_module(module)
    return module


def tapes_for(outlines):
    """Every outline as a key tape, via the compiler's own parser."""
    joined = "\n".join(outlines) + "\n"
    out = subprocess.run(
        [STFST, "tape", "--system", SYSTEM], input=joined,
        capture_output=True, text=True, check=True).stdout
    table = {}
    for line in out.splitlines():
        fields = line.split("\t")
        if len(fields) >= 2 and fields[1] != "!":
            table[fields[0]] = fields[1]
    return table


def stroke(left="", ao="", star=False, eu="", right=""):
    """A Plover stroke assembled from its fields.

    Notation is positional and unforgiving: the star sits between `AO` and `EU`,
    and the hyphen appears only when nothing in the middle already separates the
    banks. Writing `TEU-BG` or `TAOEU*` by hand made Python reject the stroke and
    looked like a grammar bug for a while.
    """
    out = left + ao + ("*" if star else "") + eu
    if right:
        if not (ao or eu or star):
            out += "-"
        out += right
    return out


def split_vowel(keys):
    """A vowels-table key as (ao, star, eu)."""
    star = "*" in keys
    body = keys.replace("*", "").replace("-", "")
    return ("".join(c for c in body if c in "AO"), star,
            "".join(c for c in body if c in "EU"))


def case(shrimple, strokes, tapes_of):
    """One golden line, or None if the case says nothing about this table."""
    tapes = [tapes_of.get(s) for s in strokes]
    if any(t is None for t in tapes):
        return None
    try:
        answer = shrimple.lookup(tuple(strokes))
    except (KeyError, IndexError):
        answer = None
    if answer is None:
        return "/".join(tapes)                      # no entry
    if "{" in answer and answer != "{Shrimple}":
        return None
    if answer == "{Shrimple}":
        answer = "Shrimple"
    return "/".join(tapes) + "\t" + answer


def main(path):
    shrimple = load(path)
    lines = [
        "! Shrimple. Expectations come from Shrimple-WSI-English.py, so this file",
        "! is an oracle and not a snapshot of our output.",
        "! Generated by scripts/gen-golden-shrimple.py; edit that, not this.",
        "^\tShrimple",
    ]
    seen = {"^"}
    wanted = []

    def add(strokes, note=None):
        wanted.append((list(strokes), note))

    # Each table on its own: every entry, plus the whole left and right banks so
    # that a segmentation of the awkward cases is exercised.
    add(["^", stroke(left="S", ao="A")], "starters, one entry at a time")
    for keys in shrimple.starter_letter:
        if keys:
            add(["^", stroke(left=keys, ao="A")])
    add(["^", stroke(ao="A")], "vowels")
    for keys in shrimple.vowels:
        if keys.strip("-*"):
            ao, star, eu = split_vowel(keys)
            add(["^", stroke(left="T", ao=ao, star=star, eu=eu)])
    add(["^", stroke(left="T", ao="A", right="F")], "enders")
    for keys in shrimple.ender_letter:
        if keys:
            add(["^", stroke(left="T", ao="A", star="*" in keys,
                             right=keys.replace("*", ""))])

    # Segmentation, exhaustively. A quarter of the left-bank chords and a sixth of
    # the right-bank ones have more than one fewest-piece cut, so the tiebreak
    # needs every chord and not a handful.
    for r in range(1, 8):
        for combo in itertools.combinations("STKPWHR", r):
            add(["^", stroke(left="".join(combo), ao="A")])
    for r in range(1, 6):
        for combo in itertools.combinations("FRPBLGTSDZ", r):
            add(["^", stroke(left="T", ao="A", right="".join(combo))])
    # The same again with the asterisk, which one piece of the cut claims.
    for r in range(1, 5):
        for combo in itertools.combinations("FRPBLGTSDZ", r):
            add(["^", stroke(left="T", ao="A", star=True, right="".join(combo))])

    # Whole syllables, then multi-stroke words.
    for left, vowel, right in itertools.product(
        ("T", "PW", "KR", ""), ("A", "AO", "EU", ""), ("", "F", "BG", "*BG")
    ):
        ao, star, eu = split_vowel(vowel + right[:1] if right.startswith("*") else vowel)
        add(["^", stroke(left=left, ao=ao, star=right.startswith("*"), eu=eu,
                         right=right.lstrip("*"))])
    add(["^", "TAP", "KAT"], "multi-stroke words")
    add(["^", "TPH", "AO", "-BG"])
    add(["^", "#TAP"], "# capitalises the syllable")
    add(["^", "TAP", "#KAT"])
    add(["^", "SKWRAOEU", "TPHAOF", "PWA"])

    tapes_of = tapes_for(sorted({s for strokes, _ in wanted for s in strokes}))
    for strokes, note in wanted:
        line = case(shrimple, strokes, tapes_of)
        if line is None:
            continue
        key = line.split("\t")[0]
        if key in seen:
            continue
        seen.add(key)
        if note:
            lines.append("! " + note)
        lines.append(line)

    print("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1
         else os.path.expanduser("~/.config/plover/Shrimple-WSI-English.py"))
